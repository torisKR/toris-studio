//! Host-side check for factory requests. The webview cannot pass a command, path, or token
//! through to the agent runtime; only these fields are forwarded.
use serde_json::{json, Value};
use std::sync::Arc;

use crate::agent_runtime::AgentRuntime;

/// Shared execution boundary. Each caller must authenticate and authorize its own
/// entry point before calling these functions; inputs are validated here again.
pub async fn preview(runtime: &Arc<AgentRuntime>, input: &Value) -> Result<Value, String> {
    let request = parse_request(input)?;
    runtime
        .call("factory.preview", request["input"].clone())
        .await
}

pub async fn start(runtime: &Arc<AgentRuntime>, input: &Value) -> Result<Value, String> {
    start_with_id(runtime, input, None).await
}

/// The optional id is generated by the authenticated host, never by the client.
pub async fn start_with_id(
    runtime: &Arc<AgentRuntime>,
    input: &Value,
    run_id: Option<uuid::Uuid>,
) -> Result<Value, String> {
    let request = parse_request(input)?;
    let mut params = json!({
        "project": "", "task": request["task"], "workflow": request["workflow"],
        "host": true, "input": request["input"],
    });
    if let Some(id) = run_id {
        params["runId"] = json!(id);
        params["origin"] = json!("mobile");
    }
    runtime.call("run.start", params).await
}

pub async fn status(runtime: &Arc<AgentRuntime>, run_id: &str) -> Result<Value, String> {
    let run = runtime.call("run.get", json!({ "runId": run_id })).await?;
    if !matches!(
        run["workflow"].as_str(),
        Some("game-factory" | "app-factory")
    ) {
        return Err("이 화면에서 다룰 수 있는 작업이 아닙니다.".into());
    }
    Ok(run)
}

pub async fn cancel(runtime: &Arc<AgentRuntime>, run_id: &str) -> Result<Value, String> {
    status(runtime, run_id).await?;
    runtime.call("run.cancel", json!({ "runId": run_id })).await
}

const KEYS: &[&str] = &["brief", "kind", "view", "orientation", "resumeProject"];

pub fn parse_request(input: &Value) -> Result<Value, String> {
    let object = input.as_object().ok_or("요청 형식을 확인하세요.")?;
    for key in object.keys() {
        if !KEYS.contains(&key.as_str()) {
            return Err(format!("{key}: 허용되지 않은 필드입니다."));
        }
    }
    let kind = object.get("kind").and_then(Value::as_str).unwrap_or("game");
    if kind != "game" && kind != "app" {
        return Err("종류를 확인하세요.".into());
    }
    let view = optional_enum(object.get("view"), &["2d", "3d", "ui"], "화면")?;
    let orientation = optional_enum(
        object.get("orientation"),
        &["landscape", "portrait"],
        "방향",
    )?;
    let brief = object
        .get("brief")
        .and_then(Value::as_str)
        .unwrap_or("")
        .trim();
    if brief.chars().count() > 2000 {
        return Err("요청이 너무 깁니다.".into());
    }
    if brief
        .chars()
        .any(|ch| ch.is_control() && ch != '\n' && ch != '\r' && ch != '\t')
        || brief.contains("$(")
        || brief.contains("sk-ant-")
        || brief.contains("sk-or-")
    {
        return Err("요청에 명령이나 비밀값을 넣을 수 없습니다.".into());
    }
    let resume = object
        .get("resumeProject")
        .and_then(Value::as_str)
        .unwrap_or("");
    if !resume.is_empty() && !is_slug(resume) {
        return Err("프로젝트 이름을 확인하세요.".into());
    }
    if brief.is_empty() && resume.is_empty() {
        return Err("요청을 입력하세요.".into());
    }
    let mut clean = json!({ "kind": kind });
    if !brief.is_empty() {
        clean["brief"] = json!(brief);
    }
    if let Some(view) = view {
        clean["view"] = json!(view);
    }
    if let Some(orientation) = orientation {
        clean["orientation"] = json!(orientation);
    }
    if !resume.is_empty() {
        clean["resumeProject"] = json!(resume);
    }
    Ok(json!({
        "workflow": if kind == "app" { "app-factory" } else { "game-factory" },
        "task": brief,
        "input": clean,
    }))
}

fn optional_enum(
    value: Option<&Value>,
    allowed: &[&str],
    label: &str,
) -> Result<Option<String>, String> {
    let Some(value) = value else { return Ok(None) };
    let text = value
        .as_str()
        .ok_or_else(|| format!("{label}을 확인하세요."))?;
    if !allowed.contains(&text) {
        return Err(format!("{label}을 확인하세요."));
    }
    Ok(Some(text.to_owned()))
}

pub(crate) fn is_slug(value: &str) -> bool {
    let mut chars = value.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    first.is_ascii_lowercase()
        && value.len() >= 2
        && value.len() <= 40
        && value
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
}

#[cfg(test)]
mod tests {
    use super::{cancel, parse_request, preview, start, status};
    use crate::agent_runtime::{node_path, AgentRuntime};
    use serde_json::json;
    use std::sync::Arc;

    #[test]
    fn requests_keep_only_closed_fields() {
        let parsed = parse_request(
            &json!({"brief": "도트 게임", "kind": "game", "view": "2d", "command": "rm"}),
        )
        .unwrap_err();
        assert!(parsed.contains("command"));
        assert!(parse_request(&json!({"brief": "게임 $(rm)"})).is_err());
        assert!(parse_request(&json!({"brief": "게임", "resumeProject": "../x"})).is_err());
        let ok =
            parse_request(&json!({"brief": "할 일 앱", "kind": "app", "orientation": "portrait"}))
                .unwrap();
        assert_eq!(ok["workflow"], "app-factory");
        assert!(ok["input"].get("command").is_none());
        assert_eq!(ok["input"]["orientation"], "portrait");
    }

    #[tokio::test]
    async fn shared_factory_operations_validate_inputs_and_reject_other_workflows() {
        let script = r#"const rl=require('node:readline').createInterface({input:process.stdin});
console.log(JSON.stringify({event:'ready',version:'test'}));
rl.on('line',l=>{const m=JSON.parse(l);let result;
 if(m.method==='run.get') result={runId:m.params.runId,workflow:m.params.runId==='factory'?'game-factory':'coding'};
 else result=m.params;
 console.log(JSON.stringify({id:m.id,ok:true,result}));
});"#;
        let runtime = Arc::new(AgentRuntime::with_launcher(
            node_path().expect("node for factory test"),
            vec!["-e".into(), script.into()],
            Box::new(|| Ok(json!({}))),
        ));
        let input = json!({"brief": "낚시 게임", "kind": "game"});
        assert_eq!(
            preview(&runtime, &input).await.unwrap()["brief"],
            "낚시 게임"
        );
        let started = start(&runtime, &input).await.unwrap();
        assert_eq!(started["workflow"], "game-factory");
        assert_eq!(started["host"], true);
        assert!(start(&runtime, &json!({"brief":"게임", "host":true}))
            .await
            .is_err());
        assert_eq!(
            status(&runtime, "factory").await.unwrap()["runId"],
            "factory"
        );
        assert!(status(&runtime, "other").await.is_err());
        assert!(cancel(&runtime, "other").await.is_err());
        assert_eq!(
            cancel(&runtime, "factory").await.unwrap()["runId"],
            "factory"
        );
        runtime.stop().await;
    }
}
